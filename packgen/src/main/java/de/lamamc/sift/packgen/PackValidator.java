package de.lamamc.sift.packgen;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Set;
import java.util.function.Predicate;
import java.util.stream.Stream;

/**
 * Checks that every model and texture the resource pack refers to exists, either in the pack itself or
 * (for the minecraft namespace) in the vanilla client.
 */
public final class PackValidator {

    private final Path packRoot;
    private final Predicate<String> vanillaAsset;
    private final ImportReport report;
    private final Set<String> checkedModels = new HashSet<>();

    /** @param vanillaAsset whether the vanilla client has an asset path (e.g. assets/minecraft/models/block/stone.json) */
    public PackValidator(Path packRoot, Predicate<String> vanillaAsset, ImportReport report) {
        this.packRoot = packRoot;
        this.vanillaAsset = vanillaAsset;
        this.report = report;
    }

    public void validate() throws IOException {
        for (Path file : jsonFiles("assets/minecraft/blockstates")) {
            collect(read(file), "model", model -> model(model, file));
        }
        for (Path file : jsonFiles("assets/the_sift/items")) {
            collect(read(file), "model", model -> model(model, file));
        }
    }

    private void model(String ref, Path from) {
        String id = namespaced(ref);
        if (!checkedModels.add(id)) {
            return;
        }
        String path = asset(id, "models", ".json");
        Path inPack = packRoot.resolve(path);
        if (Files.isRegularFile(inPack)) {
            JsonObject model = read(inPack);
            if (model.has("parent")) {
                model(model.get("parent").getAsString(), inPack);
            }
            if (model.get("textures") instanceof JsonObject textures) {
                textures.entrySet().forEach(e -> texture(e.getValue(), inPack));
            }
        } else if (!id.startsWith("minecraft:") || !vanillaAsset.test(path)) {
            report.error("Missing model " + id + " (used in " + packRoot.relativize(from) + ")");
        }
    }

    private void texture(JsonElement value, Path from) {
        String ref = value.isJsonObject() ? value.getAsJsonObject().get("sprite").getAsString() : value.getAsString();
        if (ref.startsWith("#")) {
            return;
        }
        String id = namespaced(ref);
        if (id.startsWith("minecraft:trims/")) {
            // armor trim sprites are generated by the atlas (paletted_permutations), they have no file
            return;
        }
        String path = asset(id, "textures", ".png");
        if (!Files.isRegularFile(packRoot.resolve(path)) && !(id.startsWith("minecraft:") && vanillaAsset.test(path))) {
            report.error("Missing texture " + id + " (used in " + packRoot.relativize(from) + ")");
        }
    }

    private static String namespaced(String ref) {
        return ref.contains(":") ? ref : "minecraft:" + ref;
    }

    private static String asset(String id, String kind, String ext) {
        String[] parts = id.split(":", 2);
        return "assets/" + parts[0] + "/" + kind + "/" + parts[1] + ext;
    }

    /** Every string value of the given key, anywhere in the tree. */
    private static void collect(JsonElement json, String key, java.util.function.Consumer<String> sink) {
        if (json.isJsonObject()) {
            for (var e : json.getAsJsonObject().entrySet()) {
                if (e.getKey().equals(key) && e.getValue().isJsonPrimitive()) {
                    sink.accept(e.getValue().getAsString());
                } else {
                    collect(e.getValue(), key, sink);
                }
            }
        } else if (json.isJsonArray()) {
            json.getAsJsonArray().forEach(el -> collect(el, key, sink));
        }
    }

    private Stream<Path> walk(String dir) throws IOException {
        Path root = packRoot.resolve(dir);
        return Files.isDirectory(root) ? Files.walk(root) : Stream.empty();
    }

    private java.util.List<Path> jsonFiles(String dir) throws IOException {
        try (Stream<Path> walk = walk(dir)) {
            return walk.filter(p -> p.toString().endsWith(".json")).toList();
        }
    }

    private static JsonObject read(Path file) {
        try {
            return JsonParser.parseString(Files.readString(file)).getAsJsonObject();
        } catch (IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
    }
}

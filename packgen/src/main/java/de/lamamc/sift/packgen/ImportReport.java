package de.lamamc.sift.packgen;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/** Collects what the import left out or simplified, grouped by topic, and renders it as Markdown. */
public final class ImportReport {

    private final Map<String, TreeSet<String>> sections = new TreeMap<>();
    private final List<String> errors = new ArrayList<>();

    public void note(String section, String line) {
        sections.computeIfAbsent(section, k -> new TreeSet<>()).add(line);
    }

    public void error(String line) {
        errors.add(line);
    }

    public List<String> errors() {
        return errors;
    }

    public TreeSet<String> section(String name) {
        return sections.getOrDefault(name, new TreeSet<>());
    }

    public String toMarkdown(String header) {
        StringBuilder sb = new StringBuilder("# ").append(header).append("\n\n");
        sb.append("Generated by packgen, do not edit by hand.\n");
        if (!errors.isEmpty()) {
            sb.append("\n## Errors\n\n");
            errors.forEach(e -> sb.append("- ").append(e).append('\n'));
        }
        sections.forEach((name, lines) -> {
            sb.append("\n## ").append(name).append(" (").append(lines.size()).append(")\n\n");
            lines.forEach(l -> sb.append("- ").append(l).append('\n'));
        });
        return sb.toString();
    }
}
